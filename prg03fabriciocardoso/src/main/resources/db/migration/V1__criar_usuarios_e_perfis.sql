CREATE TABLE perfis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    descricao VARCHAR(255)
);

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_usuario VARCHAR(31) NOT NULL,
    nome VARCHAR(255),
    cpf VARCHAR(255),
    genero VARCHAR(255),
    dataNascimento VARCHAR(255),
    telefone VARCHAR(255),
    email VARCHAR(255),
    login VARCHAR(255),
    senha VARCHAR(255),
    status VARCHAR(255) CHECK (status IN ('ATIVO', 'INATIVO')),
    perfil_ativo_id BIGINT REFERENCES perfis(id),
    CONSTRAINT uk_usuarios_login UNIQUE (login)
);

CREATE TABLE usuario_perfis (
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    perfil_id BIGINT NOT NULL REFERENCES perfis(id)
);
